def text_width(s, scale=2):
    return len(s) * 6 * scale

def draw_text(buf, W, H, x, y, s, color, scale=2):
    cx = int(x)
    for ch in s:
        g = GLYPHS.get(ch)
        if g is None:
            g = GLYPHS.get(ch.upper(), GLYPHS["?"])
        for row, bits in enumerate(g):
            for col, bit in enumerate(bits):
                if bit == "1":
                    px, py = cx + col * scale, int(y) + row * scale
                    if 0 <= px < W - scale and 0 <= py < H - scale:
                        for dy in range(scale):
                            b = ((py + dy) * W + px) * 3
                            buf[b:b + scale * 3] = bytes(color) * scale
        cx += 6 * scale
