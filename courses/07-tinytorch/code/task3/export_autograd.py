# -*- coding: utf-8 -*-
"""TinyTorch Module 06 -> tinytorch/core/autograd.py export script (mini nbdev export).

Usage (run in tinytorch repo root):
    python export_autograd.py            # export 06_autograd -> tinytorch/core/autograd.py
    python export_autograd.py --dry-run  # only print cell statistics, do not write

Note: jupytext percent-format module source is split into cells by '# %%';
      only cells carrying a '#| export' directive and no '#| hide' are exported,
      consistent with how modules 01-05 were exported (see headers in tinytorch/core/*.py).
"""
import argparse
import sys
from pathlib import Path

SRC = "src/06_autograd/06_autograd.py"
DST = "tinytorch/core/autograd.py"
TARGET = "core.autograd"


def find_repo() -> Path:
    candidates = [
        Path.cwd(),
        Path(__file__).resolve().parents[4] / "_tmp_tt_src" / "tinytorch",
        Path(__file__).resolve().parent / "tinytorch",
    ]
    for c in candidates:
        if (c / SRC).exists():
            return c
    raise SystemExit("tinytorch repo not found (should contain %s)" % SRC)


def split_cells(lines):
    cells, cur = [], []
    for ln in lines:
        if ln.startswith("# %%"):
            cells.append(cur)
            cur = [ln]
        else:
            cur.append(ln)
    cells.append(cur)
    return [c for c in cells if c]


def export(src_path: Path) -> str:
    lines = src_path.read_text(encoding="utf-8").splitlines()
    out = []
    for cell in split_cells(lines):
        directives = [l.strip() for l in cell if l.startswith("#|")]
        if not any(d.startswith("#| export") for d in directives):
            continue
        if any(d.startswith("#| hide") for d in directives):
            continue
        code = "\n".join(l for l in cell if not l.startswith("#|")).strip("\n")
        if code.strip():
            out.append(code)
    header = (
        "# AUTO-GENERATED by mini nbdev export from 06_autograd.py\n"
        "# target: %s\n" % TARGET
    )
    return header + "\n\n\n".join(out) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--dry-run", action="store_true")
    args = ap.parse_args()

    repo = find_repo()
    src = repo / SRC
    dst = repo / DST
    # 若目标已由官方 tito(nbdev) 导出(文件头含 AUTOGENERATED), 不覆盖, 保持官方产物
    if dst.exists() and "AUTOGENERATED" in dst.read_text(encoding="utf-8", errors="replace")[:200]:
        print("[export] target already produced by official tito/nbdev export, skip:")
        print("        ", dst)
        print("[export] (如需用本脚本重新生成, 先删除该文件)")
        return 0
    code = export(src)
    print("[export] source :", src)
    print("[export] target :", dst)
    print("[export] bytes  :", len(code.encode("utf-8")))
    if args.dry_run:
        print("[export] dry-run, no file written")
        return 0
    dst.parent.mkdir(parents=True, exist_ok=True)
    dst.write_text(code, encoding="utf-8")
    print("[export] wrote  :", dst)
    return 0


if __name__ == "__main__":
    sys.exit(main())

